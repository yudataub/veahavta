_old = None


def old_map():
    global _old
    if _old is None:
        p = os.path.join(os.path.dirname(__file__), "old_catalog_map.json")
        with open(p, encoding="utf-8") as f:
            _old = json.load(f)
    return _old


def classify(name):
    """שם קובץ (עם סיומת) → id של נושא."""
    if re.match(r"part_\d+", name, re.I):
        return "compil"
    old = old_map().get(name)
    old = OLD_REMAP.get(old, old)
    if old and old != "other" and old in IDS:
        return old
    low = name.lower()
    for tid, rx in SPEAKERS + THEMES:
        if re.search(rx, low, re.I):
            return tid
    return "other"


def clean_title(name):
    t = name.rsplit(".", 1)[0]
    t = re.sub(r"\.(wmv|avi|mp4)$", "", t, flags=re.I)        # "x.avi.mp3"
    m = re.match(r"part_(\d+)_?(.*)$", t, re.I)
    if m:
        t = (m.group(2) or "רצף").strip()
        t = re.sub(r"\s*ועוד$", "", t).rstrip(".… ") + " ועוד… (רצף %d)" % int(m.group(1))
    t = t.replace("_", " ")
    return " ".join(t.split())


def series_key(title):
    """הכותרת עד " - " הראשון — מועמד לשם סדרה (נבחר רק אם יש לפחות 3 כאלה בנושא)."""
    for sep in (" - ", " – ", "- "):
        if sep in title:
            k = title.split(sep, 1)[0]
            k = re.sub(r"(פרק|חלק|שיעור)?\s*#?\d+", " ", k)      # מספרי פרקים לא מפצלים סדרה
            k = " ".join(k.split()).strip(" #.-–")
            if 4 <= len(k) <= 60:
                return k
    return ""
